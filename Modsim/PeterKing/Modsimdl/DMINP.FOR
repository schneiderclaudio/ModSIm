      SUBROUTINE DMINP(JobPath,ExitValue,DiagFile)
C     ********************************************
C     Initiates the data input phase for the simulation.
C     This file generated by program DIMINP.FOR

      USE MSFLIB
      USE GLOBALS
      CHARACTER*255 JobPath
      INTEGER*4 ExitValue, DiagFile

      CHARACTER*4 NAMES(  7),NAM(100)
      INTEGER INDPP( 50,2),NDCL(  5),NGCL(  5),NSCL(  5),NVR(  5
     *),INDCNC(  5),CONCT(  5,4)
      INTEGER INDPAR(100,2),OUTP(10),UNTYP(100),
     *SCM(100,3),UNUM(100),B(100)
      REAL SIZ( 35), PROP(  7),GRM( 22,  7),GRV( 22,  7),PPROP(1000)
      REAL STRV( 7702),FD( 35),FG( 22),FS( 10),UNTPAR(5000),WTR(100,2),
     *WTRFUN(100)
      NDCM=  35
      NGCM=  22
      NSCM=  10
      NPPM=  50
      NUMM= 100
      NSMM= 100
      NCNCT=   5
      NMIN=   7
      NCYG= 32768
      NVARM= 7702

      WRITE(Diagfile,1001)
 1001 FORMAT(' Will now enter the subroutine to read the input data')
      CALL INPT(NPPM,NUMM,NSMM,NCNCT,NGCM,NMIN,NCYG,CONCT,INDPP,INDPAR,
     *SCM,WTR,GRM,GRV,NAMES,NAM,WTRFUN,
     *NDCL,NGCL,NSCL,NVARM,NVR,INDCNC,NDCM,NGCM,NSCM,
     *SIZ,OUTP,UNTYP,UNUM,B,PROP,PPROP,STRV,FD,FG,FS,UNTPAR,
     *JobPath,ExitValue,DiagFile)
      RETURN
      END
