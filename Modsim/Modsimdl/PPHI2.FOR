      SUBROUTINE PPHI2(JobPath,ExitValue,DiagFile)
C     ********************************************
C     Initiates the ordering phase for the simulation.
C     This file generated by program DIMINP.FOR
      USE MSFLIB
      USE GLOBALS
      CHARACTER*255 JobPath
      INTEGER*4 ExitValue, DiagFile

      INTEGER*2 COEF(100),INDNP(100),PTHVEC( 500),INDPTH(100),PTHI(100),
     *BLANK(100),NODFED(100),INDVAL(100),INDFT(100)
      INTEGER*2 SCM(100,3),WT(100),UNIT(100),UNOUT(100),STRM(100)
      INTEGER*2 STRVEC(600),INDSV(100),INVSV(600),INDISV(100)
      INTEGER*2 NOUT(100),IOUT(100),PATH(100),CYCVEC(500)
      INTEGER*2 INDCYC(100),NINPU(100),NINPN(100),NODINP(100)
      INTEGER*2 NODOUT(100),INDN(100),CYCGRP(100),INDCG( 32),GRPVEC(100)
      INTEGER*2 INDGRP(100),NODUNT(100),PLINP(100),NDINAV(100)
      INTEGER*2 UNINAV(100),TEAR(100),INDT(100),ORDUNT(100),INDORD(100)
      INTEGER*2 B(100),E(262144),G(262144),PLOUT(100)
      INTEGER*4 STRCYC(100),GRSTCY(100),M(262144)
      LOGICAL   BLOCK(100),CIRCUT(100),PATHST(100),USEDST(100)
      LOGICAL   USEDCY(100),STRGRP(100),UNTGRP(100)
      ExitValue = -1
      NSSM= 100
      NCYG=262144
      WRITE(Diagfile,1001)
 1001 FORMAT(' Will now enter the ordering subroutine')
      CALL ORDER(SCM,NSSM,NCYG,
     *WT,UNIT,UNOUT,STRM,STRVEC,INDSV,INVSV,INDISV,
     *NOUT,IOUT,PATH,
     *CYCVEC,INDCYC,NINPU,NINPN,NODINP,NODOUT,INDN,CYCGRP,
     *INDCG,GRPVEC,INDGRP,NODUNT,
     *PLINP,NDINAV,UNINAV,TEAR,INDT,ORDUNT,INDORD,B,E,G,
     *PLOUT,STRCYC,GRSTCY,M,
     *BLOCK,CIRCUT,PATHST,USEDST,USEDCY,STRGRP,UNTGRP,
     *COEF,INDNP,PTHVEC,INDPTH,PTHI,BLANK,NODFED,INDVAL,INDFT,
     *JobPath,ExitValue,DiagFile)
      RETURN
      END
